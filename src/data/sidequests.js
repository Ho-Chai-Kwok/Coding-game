// Most lessons are still a quiz (concept check). A lesson with
// `type: "terminal"` instead gets a real, typeable command-line sandbox —
// see components/TerminalChallenge.jsx and data/*Sim.js (one small command
// interpreter per tool: git, bash, docker, npm, ...). That's used for
// lessons that are actually about *doing* something (typing a real command
// and seeing real-looking output), not just recalling a definition. Every
// raw field on the lesson is passed through as-is — each tool's
// `xInitialState(content)` picks out whichever ones it understands, so
// adding a new tool never requires touching this transform.
function buildContent(l, li, total) {
  if (l.type === "terminal") {
    return { ...l, instructions: l.instructions, tool: l.tool ?? "git" };
  }
  // Real JS execution, reusing the exact same CodeChallenge/runJsCode path
  // the main learning worlds use — genuinely run and graded, not simulated.
  if (l.type === "code") {
    return { ...l };
  }
  return {
    type: "quiz",
    tutorial: l.tutorial,
    example: l.example,
    instructions: l.instructions ?? `Lesson ${li + 1} of ${total}`,
    question: l.question,
    options: l.options,
    correctIndex: l.correctIndex,
    explanation: l.explanation,
  };
}

export const sidequests = RAW_QUESTS.map((q, qi) => {
  const id = `sq-${qi + 1}`;
  return {
    id,
    name: q.name,
    icon: q.icon,
    from: q.from,
    to: q.to,
    tags: q.tags ?? [],
    totalLessons: q.lessons.length,
    lessons: q.lessons.map((l, li) => ({
      id: `${id}-${li + 1}`,
      questId: id,
      lessonNumber: li + 1,
      title: l.title,
      character: q.icon,
      status: li === 0 ? "unlocked" : "locked",
      content: buildContent(l, li, q.lessons.length),
    })),
  };
});
